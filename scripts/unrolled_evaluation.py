from src.unrolled import SpectralOperator, UnrolledTikhonov, normalised_backprojection  # noqa: E402

VARIANTS = ("noiseless", "noise")
TRAIN_SEEDS = (0, 1, 2, 3, 4)
ITERATIONS, EPOCHS, BATCH_SIZE, LR = 5, 200, 8, 1e-3
TRAIN_NOISE_SEED = 555_000   # training and validation noise; independent of NOISE_SEED (test)
REL_STDS = [s for _, s in NOISE_LEVELS]
CKPT_DIR = "experiments/unrolled"
MISMATCH_DELTAS = (0.01, 0.02)
MISMATCH_LEVELS = [(l, s) for l, s in NOISE_LEVELS if l in ("noiseless", "high")]
OUTPUT_NAMES = ("unrolled_results.json", "unrolled_per_image.npz", "unrolled_results.txt", "unrolled_noise.png")


class Physics:
    """Forward matrices, their spectral form and back-projection, for both sensor counts."""

    def __init__(self, device):
        self.device = device
        self.solvers, self.spectral = {}, {}
        for k in SENSOR_COUNTS:
            path = f"data/tikhonov_A_{k}.npy"
            if not os.path.exists(path):
                raise SystemExit(f"{path} is missing; run scripts/tikhonov_evaluation.py first.")
            self.solvers[k] = Tikhonov(np.load(path))
            self.spectral[k] = SpectralOperator(self.solvers[k].AtA)
        self.operators = [self.spectral[k].tensors(device) for k in SENSOR_COUNTS]

    def backproject(self, Y, n_sensors):
        """Flattened recordings (list, one per image) -> (N, n_pixels) float64 tensor on the device."""
        b = np.zeros((len(Y), GRID_SIZE * GRID_SIZE))
        for k in SENSOR_COUNTS:
            m = np.nonzero(n_sensors == k)[0]
            if len(m):
                b[m] = normalised_backprojection(self.solvers[k].A, self.spectral[k].norm, np.stack([Y[i] for i in m]))
        return torch.as_tensor(b, dtype=torch.float64, device=self.device)

    def geometry_index(self, n_sensors):
        return torch.as_tensor([SENSOR_COUNTS.index(int(k)) for k in n_sensors], device=self.device)


def add_relative_noise(clean, rel_stds, rng):
    """Noise model of add_sensor_noise (sigma = rel_std * RMS of the clean recording), per recording."""
    return [c if r == 0.0 else c + rng.normal(0.0, r * float(np.sqrt(np.mean(c ** 2))), size=c.shape).astype(c.dtype)
            for c, r in zip(clean, rel_stds)]


def new_model():
    return UnrolledTikhonov(geometries=SENSOR_COUNTS, iterations=ITERATIONS)


def train(physics, clean, splits, variant, seed, checkpoint_path, epochs=EPOCHS, verbose=False):
    """Train one network. `clean` and `splits` hold the train/val recordings and arrays."""
    device = physics.device
    ensure_new_checkpoint(checkpoint_path, device=device)
    np.random.seed(seed)
    torch.manual_seed(seed)
    target = {n: torch.from_numpy(splits[n]["phantom"]).unsqueeze(1).float().to(device) for n in ("train", "val")}
    geom = {n: physics.geometry_index(splits[n]["n_sensors"]) for n in ("train", "val")}
    n_train = len(clean["train"])

    if variant == "noise":
        val_rng = np.random.default_rng(TRAIN_NOISE_SEED + 1)
        val_Y, val_idx = [], []
        for r in REL_STDS:  # every validation image once at each level
            val_Y += add_relative_noise(clean["val"], [r] * len(clean["val"]), val_rng)
            val_idx += list(range(len(clean["val"])))
        val_idx = np.array(val_idx)
        train_rng = np.random.default_rng(TRAIN_NOISE_SEED + 1000 * (seed + 1))
    else:
        val_Y, val_idx = clean["val"], np.arange(len(clean["val"]))
    b_val = physics.backproject(val_Y, splits["val"]["n_sensors"][val_idx])
    val_idx_t = torch.as_tensor(val_idx, device=device)
    b_train = physics.backproject(clean["train"], splits["train"]["n_sensors"])

    model = new_model().to(device)
    opt = torch.optim.Adam(model.parameters(), lr=LR)
    loss_fn = nn.MSELoss()
    best, best_epoch, history = float("inf"), None, []
    os.makedirs(os.path.dirname(checkpoint_path) or ".", exist_ok=True)
    for epoch in range(epochs):
        if variant == "noise":
            levels = train_rng.choice(REL_STDS, size=n_train)
            b_train = physics.backproject(add_relative_noise(clean["train"], levels, train_rng), splits["train"]["n_sensors"])
        model.train()
        perm = torch.randperm(n_train)
        for i in range(0, n_train, BATCH_SIZE):
            idx = perm[i:i + BATCH_SIZE].to(device)
            opt.zero_grad()
            loss = loss_fn(model(b_train[idx], geom["train"][idx], physics.operators, GRID_SIZE), target["train"][idx])
            loss.backward()
            opt.step()
        model.eval()
        with torch.no_grad():
            val_loss = loss_fn(model(b_val, geom["val"][val_idx_t], physics.operators, GRID_SIZE),
                               target["val"][val_idx_t]).item()
        history.append(val_loss)
        if val_loss < best:
            best, best_epoch = val_loss, epoch
            torch.save({"model_state": cpu_state_dict(model), "epoch": epoch, "val_loss": val_loss, "seed": seed,
                        "variant": variant}, checkpoint_path)
        if verbose and (epoch % 20 == 0 or epoch == epochs - 1):
            print(f"  {variant} seed {seed} epoch {epoch + 1}/{epochs} val_loss {val_loss:.6f}", flush=True)
    return {"best_epoch": best_epoch, "best_val_loss": best, "val_history": history}


def load_model(path, device):
    ckpt = torch.load(path, map_location="cpu", weights_only=True)
    model = new_model()
    model.load_state_dict(ckpt["model_state"])
    return model.to(device).eval(), ckpt


def reconstruct(models, physics, Y, n_sensors):
    """{name: (N, grid, grid) float32} for recordings Y."""
    b, geom = physics.backproject(Y, n_sensors), physics.geometry_index(n_sensors)
    with torch.no_grad():
        return {name: to_numpy(model(b, geom, physics.operators, GRID_SIZE).squeeze(1)) for name, model in models.items()}


def score(per_image, key, outputs, phantoms):
    """per_image[key + (name, metric)] for every output, plus the per-image mean over the networks
    of each variant."""
    for name, img in outputs.items():
        per_image[key + (name, "psnr")] = np.array([psnr(img[i], phantoms[i]) for i in range(len(phantoms))])
        per_image[key + (name, "ssim")] = np.array([ssim(img[i], phantoms[i]) for i in range(len(phantoms))])
    for variant in VARIANTS:
        for metric in ("psnr", "ssim"):
            per_image[key + (f"unrolled_{variant}", metric)] = np.mean(
                [per_image[key + (f"{variant}_seed{s}", metric)] for s in TRAIN_SEEDS], axis=0)


def summary(values, per_seed):
    seed_means = np.array([v.mean() for v in per_seed])
    return {"mean_ci95": bootstrap_mean_ci(values), "per_seed_means": seed_means.tolist(),
            "seed_min": float(seed_means.min()), "seed_max": float(seed_means.max()),
            "seed_sd": float(seed_means.std(ddof=1))}


def main(device_choice="cpu", out_dir="report", overwrite=False):
    t0 = time.time()
    device = get_device(device_choice)
    if device.type == "mps":
        raise SystemExit("the data-consistency solves need float64, which MPS does not support; use cpu or cuda")
    out_paths = [ensure_writable(os.path.join(out_dir, n), device=device, overwrite=overwrite) for n in OUTPUT_NAMES]

    physics = Physics(device)
    domain, medium = build_domain_and_medium(GRID_SIZE)
    sensors = {k: sparse_view_sensor_array(k, RADIUS, CENTRE) for k in SENSOR_COUNTS}
    splits = {"train": np.load("data/train.npz"), "val": np.load("data/val.npz"), "test": np.load(TEST_PATH)}
    clean = {n: [simulation_done(y) for y in recordings(d["phantom"], d["n_sensors"], domain, medium, sensors)]
             for n, d in splits.items()}
    print(f"[{time.time() - t0:.0f}s] matrices, eigendecompositions and clean recordings ready", flush=True)

    # --- training ---
    models, networks = {}, {}
    for variant in VARIANTS:
        for s in TRAIN_SEEDS:
            path = f"{CKPT_DIR}/{variant}_seed{s}.pt"
            if not os.path.exists(path):
                train(physics, clean, splits, variant, s, path)
                print(f"[{time.time() - t0:.0f}s] trained {variant} seed {s}", flush=True)
            model, ckpt = load_model(path, device)
            models[f"{variant}_seed{s}"] = model
            networks[f"{variant}_seed{s}"] = {"epoch": int(ckpt["epoch"]), "val_loss": float(ckpt["val_loss"]),
                                              "mu": {str(k): model.mu()[g].tolist() for g, k in enumerate(SENSOR_COUNTS)}}

    # --- test evaluation, paired with the saved results of the other methods ---
    test, phantoms, n_s = splits["test"], splits["test"]["phantom"], splits["test"]["n_sensors"]
    ref_eval, ref_tik = np.load("report/expanded_eval_per_image.npz"), np.load("report/tikhonov_per_image.npz")
    assert np.array_equal(ref_eval["seed"], test["seed"]) and np.array_equal(ref_tik["seed"], test["seed"])
    per_image = {}
    for label, rel_std in NOISE_LEVELS:
        score(per_image, (label,), reconstruct(models, physics, noisy(clean["test"], rel_std, NOISE_SEED), n_s), phantoms)
        print(f"[{time.time() - t0:.0f}s] test noise {label} done", flush=True)

    references = {"tr_cal": lambda l, m: ref_eval[f"{l}__tr_cal__{m}"],
                  "unet": lambda l, m: ref_eval[f"{l}__unet_mean_over_seeds__{m}"],
                  "tikhonov_per_level": lambda l, m: ref_tik[f"{l}__tikhonov_per_level__{m}"],
                  "tikhonov_fixed": lambda l, m: ref_tik[f"{l}__tikhonov_fixed__{m}"]}
    results = {"protocol": __doc__.split("Outputs:")[0].strip(),
               "configuration": {"iterations": ITERATIONS, "epochs": EPOCHS, "batch_size": BATCH_SIZE, "lr": LR,
                                 "parameters": sum(p.numel() for p in new_model().parameters()),
                                 "device": str(device), "torch": torch.__version__},
               "networks": networks, "levels": [], "mismatch": []}
    for label, rel_std in NOISE_LEVELS:
        level = {"label": label, "relative_std": rel_std, "by_sensors": {}}
        for k in SENSOR_COUNTS:
            m = n_s == k
            entry = {}
            for metric in ("psnr", "ssim"):
                e = {"reference_means": {name: float(f(label, metric)[m].mean()) for name, f in references.items()}}
                for variant in VARIANTS:
                    v = per_image[(label, f"unrolled_{variant}", metric)][m]
                    e[variant] = {**summary(v, [per_image[(label, f"{variant}_seed{s}", metric)][m] for s in TRAIN_SEEDS]),
                                  **{f"minus_{name}": paired_bootstrap_ci(v, f(label, metric)[m])
                                     for name, f in references.items() if name != "tikhonov_fixed"}}
                entry[metric] = e
            level["by_sensors"][str(k)] = entry
        results["levels"].append(level)

    # --- model mismatch: data from a medium with the wrong sound speed, everything else nominal ---
    from jwave.geometry import TimeAxis

    from scripts.model_mismatch_evaluation import simulate

    ref_mis = np.load("report/model_mismatch_per_image.npz")
    assert np.array_equal(ref_mis["seed"], test["seed"])
    time_axis = TimeAxis.from_medium(medium, cfl=0.3)
    for delta in MISMATCH_DELTAS:
        _, medium_true = build_domain_and_medium(GRID_SIZE, sound_speed=DEFAULT_SOUND_SPEED * (1 + delta))
        clean_mis = [simulation_done(simulate(phantoms[i], domain, medium_true, time_axis, sensors[int(n_s[i])]))
                     for i in range(len(phantoms))]
        for label, rel_std in MISMATCH_LEVELS:
            rng = np.random.default_rng(NOISE_SEED + int(round(rel_std * 100000)))
            Y = [add_sensor_noise(c, rel_std, rng)[..., 0].reshape(-1) for c in clean_mis]
            key = (f"{delta:+.2f}", label)
            score(per_image, key, reconstruct(models, physics, Y, n_s), phantoms)
            for k in SENSOR_COUNTS:
                m = n_s == k
                row = {"delta": delta, "label": label, "sensors": k}
                for metric in ("psnr", "ssim"):
                    ref = {name: ref_mis[f"{delta:+.2f}__{label}__{name}__{metric}"][m]
                           for name in ("tr_cal", "unet_mean_over_seeds", "tikhonov")}
                    e = {"reference_means": {name: float(v.mean()) for name, v in ref.items()}}
                    for variant in VARIANTS:
                        v = per_image[key + (f"unrolled_{variant}", metric)][m]
                        e[variant] = {**summary(v, [per_image[key + (f"{variant}_seed{s}", metric)][m] for s in TRAIN_SEEDS]),
                                      "minus_tikhonov": paired_bootstrap_ci(v, ref["tikhonov"]),
                                      "minus_unet": paired_bootstrap_ci(v, ref["unet_mean_over_seeds"])}
                    row[metric] = e
                results["mismatch"].append(row)
            print(f"[{time.time() - t0:.0f}s] mismatch {delta:+.0%}, noise {label} done", flush=True)

    os.makedirs(out_dir, exist_ok=True)
    with open(out_paths[0], "w") as f:
        json.dump(results, f, indent=2)
    np.savez_compressed(out_paths[1], seed=test["seed"], n_sensors=n_s,
                        **{"__".join(key): v for key, v in per_image.items()})
    write_text(results, out_paths[2])
    plot(results, out_paths[3])
    print(f"[{time.time() - t0:.0f}s] wrote {out_dir}/unrolled_*")


def _ci(t, d):
    return f"{t[0]:+.{d}f} [{t[1]:+.{d}f}, {t[2]:+.{d}f}]"


def write_text(r, path):
    c = r["configuration"]
    L = ["Unrolled Tikhonov network (scripts/unrolled_evaluation.py)", "", r["protocol"], "",
         f"Configuration: {c['iterations']} iterations, {c['parameters']} parameters, {c['epochs']} epochs, "
         f"batch {c['batch_size']}, lr {c['lr']}, device {c['device']}", "", "Networks (best epoch, validation loss, learned mu per iteration):"]
    for name, n in r["networks"].items():
        L.append(f"  {name}: epoch {n['epoch']}, val {n['val_loss']:.6f}; "
                 + "; ".join(f"{k} sensors mu " + " ".join(f"{v:.1e}" for v in mu) for k, mu in n["mu"].items()))
    L.append("")
    for lvl in r["levels"]:
        L.append(f"== noise {lvl['label']} (relative std {lvl['relative_std']})")
        for k, entry in lvl["by_sensors"].items():
            for metric, d in (("psnr", 2), ("ssim", 3)):
                e = entry[metric]
                ref = e["reference_means"]
                L.append(f"  {k} sensors {metric.upper()}: cal TR {ref['tr_cal']:.{d}f} | U-Net {ref['unet']:.{d}f} | "
                         f"Tikhonov per level {ref['tikhonov_per_level']:.{d}f} | Tikhonov fixed {ref['tikhonov_fixed']:.{d}f}")
                for variant in VARIANTS:
                    x = e[variant]
                    m, lo, hi = x["mean_ci95"]
                    L.append(f"      unrolled, {variant}-trained: {m:.{d}f} [{lo:.{d}f}, {hi:.{d}f}] "
                             f"(5 networks {x['seed_min']:.{d}f}-{x['seed_max']:.{d}f}, sd {x['seed_sd']:.{d}f}) | "
                             f"vs Tikhonov per level {_ci(x['minus_tikhonov_per_level'], d)} | vs U-Net {_ci(x['minus_unet'], d)} | "
                             f"vs cal TR {_ci(x['minus_tr_cal'], d)}")
    L += ["", "Model mismatch (true sound speed above nominal; all methods nominal):"]
    for row in r["mismatch"]:
        for metric, d in (("psnr", 2), ("ssim", 3)):
            e = row[metric]
            ref = e["reference_means"]
            L.append(f"  c +{row['delta']:.0%}, noise {row['label']:9s}, {row['sensors']} sensors {metric.upper()}: "
                     f"cal TR {ref['tr_cal']:.{d}f} | U-Net {ref['unet_mean_over_seeds']:.{d}f} | Tikhonov {ref['tikhonov']:.{d}f}")
            for variant in VARIANTS:
                x = e[variant]
                m, lo, hi = x["mean_ci95"]
                L.append(f"      unrolled, {variant}-trained: {m:.{d}f} [{lo:.{d}f}, {hi:.{d}f}] "
                         f"(5 networks {x['seed_min']:.{d}f}-{x['seed_max']:.{d}f}) | vs Tikhonov {_ci(x['minus_tikhonov'], d)} | "
                         f"vs U-Net {_ci(x['minus_unet'], d)}")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L[-70:]))


def plot(r, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    def snr(rel_std):
        return "inf" if rel_std == 0 else "{:.0f}".format(20 * np.log10(1 / rel_std))
    labels = ["{}\n{} dB".format(l["label"], snr(l["relative_std"])) for l in r["levels"]]
    x = np.arange(len(labels))
    fig, axes = plt.subplots(1, 2, figsize=(11, 5.2), sharey=True)
    top = 95.0
    for ax, k in zip(axes, ("16", "64")):
        e = [l["by_sensors"][k]["psnr"] for l in r["levels"]]
        for key, lab, c, mk in (("tr_cal", "calibrated time-reversal", "C1", "o"), ("unet", "U-Net (mean of 5 networks)", "C0", "D"),
                                ("tikhonov_per_level", "Tikhonov, mu selected per noise level", "C2", "s")):
            ax.plot(x, np.minimum([v["reference_means"][key] for v in e], top), color=c, marker=mk, ms=4, label=lab)
        for variant, lab, c in (("noise", "unrolled Tikhonov, trained with noise", "C3"),
                                ("noiseless", "unrolled Tikhonov, trained without noise", "C4")):
            m = np.array([q[variant]["mean_ci95"][0] for q in e])
            lo = np.array([q[variant]["seed_min"] for q in e]); hi = np.array([q[variant]["seed_max"] for q in e])
            ax.plot(x, np.clip(m, 15, top), color=c, marker="^", ms=5, label=lab + " (mean of 5)")
            ax.fill_between(x, np.clip(lo, 15, top), np.clip(hi, 15, top), color=c, alpha=0.18, lw=0)
        ax.set_ylim(15, top)
        ax.set_title(f"{k} sensors", fontsize=10)
        ax.set_xticks(x, labels, fontsize=8)
        ax.set_xlabel("sensor noise level (SNR)")
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("PSNR [dB]")
    handles, names = axes[0].get_legend_handles_labels()
    fig.legend(handles, names, fontsize=8, loc="lower center", ncol=3, frameon=False)
    fig.suptitle("400 held-out test images; bands: range of the 5 networks' means", fontsize=10)
    fig.tight_layout(rect=(0, 0.1, 1, 1))
    fig.savefig(path, dpi=130)
    plt.close(fig)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--device", choices=("cpu", "cuda", "auto"), default="cpu")
    parser.add_argument("--out-dir", default="report")
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()
    main(args.device, args.out_dir, args.overwrite)
