"""Unrolled Tikhonov network (src/unrolled.py): training and evaluation on the expanded test set.

Protocol (fixed before any test result was seen):
  * Method: 5 unrolled iterations, one residual CNN (5 layers, 32 features) shared by all
    iterations, one learned weight mu per iteration and sensor count, initialised at 1e-2. The
    forward matrices are those of the Tikhonov baseline (data/tikhonov_A_{16,64}.npy). The method is
    never given the noise level.
  * Training data: the phantoms of data/train.npz (40) and data/val.npz (8), with recordings from the
    project forward model. Two training variants, 5 networks each (seeds 0-4):
      - "noiseless": clean recordings only, like the U-Net and like the "fixed" Tikhonov weight;
      - "noise":     every training recording gets, at every epoch, a relative noise level drawn
                     uniformly from the five evaluation levels (0, 0.01, 0.05, 0.2, 0.5) and fresh
                     noise from generators seeded independently of the test noise. Validation uses
                     each validation image once at each of the five levels, with fixed noise.
    MSE loss, Adam 1e-3, batch 8, 200 epochs, checkpoint with the lowest validation loss, CPU with
    deterministic algorithms. (The U-Net recipe is 60 epochs; 200 was chosen in advance, not tuned.)
  * Test data and noise: exactly the recordings of scripts/expanded_evaluation.py and
    scripts/tikhonov_evaluation.py (same 400 phantoms, noise generator, seeds and draw order), so
    results pair image by image with calibrated time reversal, the U-Net and Tikhonov.
  * Model mismatch: the data of scripts/model_mismatch_evaluation.py (true sound speed 1 % and 2 %
    above nominal, noiseless and "high" noise); the networks and matrices stay nominal.
  * Uncertainty: 95 % bootstrap intervals over test images for the mean over the 5 networks; the
    spread between networks is reported separately.

Caveat, as for Tikhonov: outside the mismatch check the test data are generated by the same discrete
forward model that the method inverts.

Outputs: report/unrolled_results.{txt,json}, report/unrolled_per_image.npz, report/unrolled_noise.png.
Requires the outputs of expanded_evaluation.py, tikhonov_evaluation.py and
model_mismatch_evaluation.py. Checkpoints go to experiments/unrolled/ (gitignored).

    python scripts/unrolled_evaluation.py
"""
